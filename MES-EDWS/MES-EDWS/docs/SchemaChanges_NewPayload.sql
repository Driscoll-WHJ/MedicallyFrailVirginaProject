/*=============================================================================
  Schema additions required to support docs/NewPayloadPost.json (CEP-ICD-003
  revision received 2026-08). Run against HR1_DMAS_POC after review by a DBA.

  This script only ADDS columns/tables. Nothing here drops or renames existing
  columns, so it is safe to run against an environment that already has the
  original TableDefinition.txt schema applied.

  Sections:
    1. Lineage columns (SOURCE_SYSTEM_CD / UPDATE_SW_FLG / VACMS_SEQUENCE_NBR /
       APPLICATION_SOURCE_CD) added to tables whose payload objects now carry
       "source" / "updatesw" / "vaCMSSequenceNum" / "applicationSource".
    2. New/changed scalar columns on existing tables (renamed or newly
       introduced fields on existing exemption objects).
    3. Brand-new tables for payload sections that had nowhere to go before
       (veteran disability, rules evaluation results, caregiver monthly hours,
       in-kind/unpaid work, and the four budget-related arrays).
=============================================================================*/

